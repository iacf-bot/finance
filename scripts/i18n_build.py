"""Build static/locales/*.js from locales/*.json (English key -> translation).

    python scripts/i18n_build.py            # writes static/locales/<code>.js for every locales/<code>.json
    python scripts/i18n_build.py --tw       # also regenerate locales/zh-TW.json from zh-CN with OpenCC (pip install opencc-python-reimplemented)

To add a language: copy locales/zh-CN.json to locales/<code>.json (e.g. ja.json), translate the values (leave a value
"" to fall back to English), set "_name", run this script, add <script src="/static/locales/<code>.js"> to index.html.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "locales", ROOT / "static" / "locales"

if "--tw" in sys.argv:
    import opencc
    cc = opencc.OpenCC("s2twp")
    zh = json.loads((SRC / "zh-CN.json").read_text("utf-8"))
    tw = {k: (cc.convert(v) if k != "_name" else "繁體中文") for k, v in zh.items()}
    old = json.loads((SRC / "zh-TW.json").read_text("utf-8")) if (SRC / "zh-TW.json").exists() else {}
    tw.update({k: v for k, v in old.get("_overrides", {}).items()})
    tw["_overrides"] = old.get("_overrides", {})
    (SRC / "zh-TW.json").write_text(json.dumps(tw, ensure_ascii=False, indent=1, sort_keys=True) + "\n", "utf-8")

OUT.mkdir(parents=True, exist_ok=True)
for f in sorted(SRC.glob("*.json")):
    d = json.loads(f.read_text("utf-8"))
    name = d.pop("_name", f.stem)
    d.pop("_overrides", None)
    js = f"/* generated by scripts/i18n_build.py from locales/{f.name} — edit the JSON, not this file */\n" \
         f"i18nAdd({json.dumps(f.stem)}, {json.dumps(name, ensure_ascii=False)}, {json.dumps(d, ensure_ascii=False, sort_keys=True, indent=0)});\n"
    (OUT / f"{f.stem}.js").write_text(js, "utf-8")
    print(f.stem, len(d), "strings")
